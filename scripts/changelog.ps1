# Usage:
#   ./scripts/changelog.ps1               -> regenerate docs/CHANGELOG.md from git log
#   ./scripts/changelog.ps1 -MarkDeployed -> mark current HEAD as deployed, then regenerate
param([switch]$MarkDeployed, [int]$Max = 100)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

function Get-RepositoryRoot {
  $root = Split-Path $PSScriptRoot -Parent
  if (-not (Test-Path (Join-Path $root '.git'))) {
    throw "Not a git repository root: $root"
  }
  return $root
}

function Get-DeployedCommitHash([string]$markerPath) {
  if (-not (Test-Path $markerPath)) { return '' }
  return (Get-Content $markerPath -Raw).Trim()
}

function Save-DeployedCommitHash([string]$markerPath) {
  $head = (git rev-parse HEAD) | Select-Object -First 1
  if (-not $head) { throw 'git rev-parse HEAD returned no commit hash.' }
  $head.Trim() | Set-Content $markerPath -NoNewline
}

function Get-DeployedCommitSet([string]$deployedHash) {
  $deployedSet = @{}
  if ($deployedHash) {
    git rev-list $deployedHash | ForEach-Object { $deployedSet[$_] = $true }
  }
  return $deployedSet
}

function Get-RecentCommitHashes([int]$count) {
  if ($count -lt 1) { throw "Max must be at least 1 (was $count)." }
  $hashes = @(git log -n $count --format=%H)
  if ($LASTEXITCODE -ne 0) { throw 'git log failed.' }
  return $hashes | Where-Object { $_ }
}

function Get-CommitDetail([string]$commitHash) {
  $parts = (git show -s --format='%ad|%s|%h' --date=format:'%Y-%m-%d %H:%M' $commitHash) -split '\|', 3
  if ($parts.Count -ne 3) { throw "Unexpected git show output for commit $commitHash." }
  return [pscustomobject]@{
    Date    = $parts[0]
    Subject = $parts[1]
    Short   = $parts[2]
  }
}

function Get-FileGroupKey([string]$filePath) {
  $segments = $filePath -split '/'
  $lastGroupIndex = [Math]::Min(2, $segments.Count - 2)
  return ($segments[0..$lastGroupIndex] -join '/')
}

function Get-GroupedChangedFiles([string]$commitHash) {
  $files = @(git show --name-only --format= $commitHash | Where-Object { $_ })
  if ($LASTEXITCODE -ne 0) { throw "git show failed for commit $commitHash." }
  if (-not $files) { return @() }
  return $files | Group-Object { Get-FileGroupKey $_ }
}

function Format-CommitEntry([string]$commitHash, [hashtable]$deployedSet) {
  $detail = Get-CommitDetail $commitHash
  $status = if ($deployedSet.ContainsKey($commitHash)) { '✅ Deployed' } else { '🕓 Pending' }
  $lines = @(
    "## $($detail.Subject)"
    "- **Status:** $status"
    "- **Date:** $($detail.Date)  |  **Commit:** ``$($detail.Short)``"
  )
  $groups = Get-GroupedChangedFiles $commitHash
  if ($groups) {
    $lines += '- **Where:**'
    foreach ($group in $groups) {
      $fileNames = ($group.Group | ForEach-Object { Split-Path $_ -Leaf }) -join ', '
      $lines += "  - ``$($group.Name)/`` ($($group.Count)): $fileNames"
    }
  }
  $lines += ''
  return $lines
}

function Write-ChangelogDocument([string]$deployedHash, [hashtable]$deployedSet, [string[]]$commitHashes, [string]$outputPath) {
  $shortDeployed = if ($deployedHash) { $deployedHash.Substring(0, 7) } else { 'none' }
  $lines = @('# Changelog', '', 'Auto-generated by scripts/changelog.ps1. Do not edit by hand.', '',
    "Last deployed commit: $shortDeployed", '')
  foreach ($commitHash in $commitHashes) {
    $lines += Format-CommitEntry $commitHash $deployedSet
  }
  $lines | Set-Content $outputPath -Encoding utf8
}

$repositoryRoot = Get-RepositoryRoot
Set-Location $repositoryRoot
$markerFile = 'docs/.last-deployed'
if ($MarkDeployed) { Save-DeployedCommitHash $markerFile }
$deployedCommit = Get-DeployedCommitHash $markerFile
$deployedCommitSet = Get-DeployedCommitSet $deployedCommit
$recentCommits = Get-RecentCommitHashes $Max
Write-ChangelogDocument $deployedCommit $deployedCommitSet $recentCommits 'docs/CHANGELOG.md'
Write-Host 'Wrote docs/CHANGELOG.md'
