# Usage:
#   ./scripts/changelog.ps1               -> regenerate docs/CHANGELOG.md from git log
#   ./scripts/changelog.ps1 -MarkDeployed -> mark current HEAD as deployed, then regenerate
param([switch]$MarkDeployed, [int]$Max = 100)
$root = Split-Path $PSScriptRoot -Parent
Set-Location $root
$marker = "docs/.last-deployed"
if ($MarkDeployed) { (git rev-parse HEAD) | Set-Content $marker -NoNewline }
$deployed = if (Test-Path $marker) { (Get-Content $marker -Raw).Trim() } else { "" }
$deployedSet = @{}
if ($deployed) { git rev-list $deployed | ForEach-Object { $deployedSet[$_] = $true } }
$out = @("# Changelog", "", "Auto-generated by scripts/changelog.ps1. Do not edit by hand.", "",
  "Last deployed commit: " + $(if ($deployed) { $deployed.Substring(0,7) } else { "none" }), "")
$hashes = git log -n $Max --format=%H
foreach ($h in $hashes) {
  $d = (git show -s --format="%ad|%s|%h" --date=format:"%Y-%m-%d %H:%M" $h) -split "\|", 3
  $status = if ($deployedSet.ContainsKey($h)) { "✅ Deployed" } else { "🕓 Pending" }
  $out += "## $($d[1])"
  $out += "- **Status:** $status"
  $out += "- **Date:** $($d[0])  |  **Commit:** ``$($d[2])``"
  $files = git show --name-only --format= $h | Where-Object { $_ }
  if ($files) {
    $out += "- **Where:**"
    $files | Group-Object { ($_ -split "/")[0..([Math]::Min(2,($_ -split "/").Count-2))] -join "/" } | ForEach-Object {
      $out += "  - ``$($_.Name)/`` ($($_.Count)): " + (($_.Group | ForEach-Object { Split-Path $_ -Leaf }) -join ", ")
    }
  }
  $out += ""
}
$out | Set-Content docs/CHANGELOG.md -Encoding utf8
Write-Host "Wrote docs/CHANGELOG.md"
